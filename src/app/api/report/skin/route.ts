// ── DAILY SKIN endpoint — v8.2 Telegram artwork rotation status ────────────
// Returns the skin currently in effect (Tehran-day deterministic) so the
// dashboard badge can prove the daily background rotation to the operator.

import { NextResponse } from "next/server";
import fs from "node:fs/promises";
import path from "node:path";
import { dailySkin, SKIN_COUNT, SKIN_NAMES, SKIN_KINDS } from "@/lib/daily-skin";

export async function GET() {
  const s = dailySkin();
  const assets = path.join(process.cwd(), "assets", "telegram");
  const exists = async (f: string) => {
    try {
      await fs.access(path.join(assets, f));
      return true;
    } catch {
      return false;
    }
  };
  // v9.4 honesty: report whether the AI style backdrop actually exists on
  // disk (generated by scripts/gen-skin-art.sh) or the legacy art piece /
  // procedural gradient is wearing the report today.
  const ready = await exists(`skin-${s.key}.png`);
  // v9.5 kind coverage: per-card-type art (LONG/SHORT/TP/STOP/EXPIRED) inside
  // today's style — the operator can see exactly which cards wear bespoke art.
  const kinds: Record<string, boolean> = {};
  for (const k of SKIN_KINDS) kinds[k] = await exists(`skin-${s.key}-${k}.png`);
  const kindReady = Object.values(kinds).filter(Boolean).length;
  return NextResponse.json({
    ok: true,
    // v9.4: key = skin-{key}.png AI backdrop (7-SKIN CYCLE, real generation);
    // artKind = legacy art-{KIND}.png fallback still reported for honesty.
    skin: {
      name: s.name, key: s.key, accent: s.accent, artKind: s.artKind,
      dayKey: s.dayKey, hueShift: s.hueShift, ready,
      kinds, kindReady, kindTotal: SKIN_KINDS.length,
    },
    cycle: { count: SKIN_COUNT, names: SKIN_NAMES },
  });
}
